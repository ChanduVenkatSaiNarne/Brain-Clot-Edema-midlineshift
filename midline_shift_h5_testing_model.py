import tensorflow as tf
import numpy as np
import cv2
import os
import matplotlib.pyplot as plt
from google.colab import files
from scipy.ndimage import center_of_mass

# Constants
PIXEL_SPACING_MM = 0.5
SLICE_THICKNESS_MM = 5
PIXEL_AREA_MM2 = PIXEL_SPACING_MM ** 2
PIXEL_VOLUME_MM3 = PIXEL_AREA_MM2 * SLICE_THICKNESS_MM

# Load all three models
clot_model = tf.keras.models.load_model("/content/unet_clot_segmentation_single_class_1000.h5", custom_objects={"dice_coefficient": lambda y_true, y_pred: 1})
edema_model = tf.keras.models.load_model("/content/unet_clot_segmentation_single_class_edema_1000.h5", custom_objects={"dice_coefficient": lambda y_true, y_pred: 1})
midline_model = tf.keras.models.load_model("/content/unet_clot_segmentation_single_class_midline_1000.h5", custom_objects={"dice_coefficient": lambda y_true, y_pred: 1})

# Upload image
uploaded = files.upload()

for filename in uploaded.keys():
    img_path = filename

    def preprocess_image(image_path, img_size=(256, 256)):
        img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
        original_img = cv2.imread(image_path)
        original_shape = (original_img.shape[1], original_img.shape[0])
        img_resized = cv2.resize(img, img_size) / 255.0
        img_resized = np.expand_dims(img_resized, axis=-1)
        return img_resized, original_img, original_shape

    img, original_img, original_shape = preprocess_image(img_path)
    input_img = np.expand_dims(img, axis=0)

    # Predict masks
    clot_mask = clot_model.predict(input_img)[0]
    edema_mask = edema_model.predict(input_img)[0]
    midline_mask = midline_model.predict(input_img)[0]

    # Resize masks
    clot_mask_resized = cv2.resize(clot_mask, original_shape, interpolation=cv2.INTER_NEAREST)
    edema_mask_resized = cv2.resize(edema_mask, original_shape, interpolation=cv2.INTER_NEAREST)
    midline_mask_resized = cv2.resize(midline_mask, original_shape, interpolation=cv2.INTER_NEAREST)

    # Binarize
    clot_binary = (clot_mask_resized > 0.5).astype(np.uint8)
    edema_binary = (edema_mask_resized > 0.5).astype(np.uint8)
    midline_binary = (midline_mask_resized > 0.5).astype(np.uint8)

    # Brain area
    brain_mask = (cv2.cvtColor(original_img, cv2.COLOR_BGR2GRAY) > 0).astype(np.uint8)
    total_brain_area_pixels = np.sum(brain_mask)
    total_brain_area_mm2 = total_brain_area_pixels * PIXEL_AREA_MM2
    brain_volume_mm3 = total_brain_area_mm2 * SLICE_THICKNESS_MM

    # Area calculations
    clot_area_pixels = np.sum(clot_binary)
    edema_area_pixels = np.sum(edema_binary)
    midline_area_pixels = np.sum(midline_binary)

    clot_area_mm2 = clot_area_pixels * PIXEL_AREA_MM2
    edema_area_mm2 = edema_area_pixels * PIXEL_AREA_MM2
    midline_shift_area_mm2 = midline_area_pixels * PIXEL_AREA_MM2

    # Volume calculations
    clot_volume_mm3 = clot_area_pixels * PIXEL_VOLUME_MM3
    edema_volume_mm3 = edema_area_pixels * PIXEL_VOLUME_MM3
    midline_shift_volume_mm3 = midline_area_pixels * PIXEL_VOLUME_MM3

    # Volume percentages
    clot_volume_percentage = (clot_volume_mm3 / brain_volume_mm3) * 100
    edema_volume_percentage = (edema_volume_mm3 / brain_volume_mm3) * 100
    midline_shift_volume_percentage = (midline_shift_volume_mm3 / brain_volume_mm3) * 100
    normal_brain_percentage = 100 - (clot_volume_percentage + edema_volume_percentage + midline_shift_volume_percentage)

    # === Clot Location Detection ===
    h, w = clot_binary.shape
    center_x = w // 2
    ys_clot, xs_clot = np.where(clot_binary == 1)
    left_clot = np.sum(xs_clot < center_x)
    right_clot = np.sum(xs_clot >= center_x)
    top_clot = np.sum(ys_clot < h // 3)
    middle_clot = np.sum((ys_clot >= h // 3) & (ys_clot < 2 * h // 3))
    bottom_clot = np.sum(ys_clot >= 2 * h // 3)
    clot_horizontal_position = "Left Hemisphere" if left_clot > right_clot else "Right Hemisphere" if right_clot > left_clot else "Center / Cannot Determine"
    clot_vertical_position = "Upper Region" if top_clot > middle_clot and top_clot > bottom_clot else "Lower Region" if bottom_clot > middle_clot else "Middle Region"
    clot_position = f"{clot_vertical_position}, {clot_horizontal_position}"

    # === Edema Location Detection ===
    ys_edema, xs_edema = np.where(edema_binary == 1)
    left_edema = np.sum(xs_edema < center_x)
    right_edema = np.sum(xs_edema >= center_x)
    top_edema = np.sum(ys_edema < h // 3)
    middle_edema = np.sum((ys_edema >= h // 3) & (ys_edema < 2 * h // 3))
    bottom_edema = np.sum(ys_edema >= 2 * h // 3)
    edema_horizontal_position = "Left Hemisphere" if left_edema > right_edema else "Right Hemisphere" if right_edema > left_edema else "Center / Cannot Determine"
    edema_vertical_position = "Upper Region" if top_edema > middle_edema and top_edema > bottom_edema else "Lower Region" if bottom_edema > middle_edema else "Middle Region"
    edema_position = f"{edema_vertical_position}, {edema_horizontal_position}"

    # === Severity Grading ===
    if midline_shift_volume_percentage >= 5.0:
        severity_grade = "Severe (Significant Midline Shift > 5%)"
        clinical_condition = "Likely mass effect, hemorrhage, or tumor"
        symptoms = [
            "Loss of consciousness",
            "Severe headache",
            "Focal neurological deficits",
            "Seizures"
        ]
    elif 3.0 < midline_shift_volume_percentage < 5.0:
        severity_grade = "Moderate (Midline Shift between 3% - 5%)"
        clinical_condition = "Possible compression or moderate edema"
        symptoms = [
            "Confusion",
            "Mild hemiparesis",
            "Headache",
            "Nausea"
        ]
    elif 0.5 < midline_shift_volume_percentage <= 3.0:
        severity_grade = "Mild (Midline Shift between 0.5% - 3%)"
        clinical_condition = "Possible localized compression or edema"
        symptoms = [
            "Mild headache",
            "Dizziness",
            "Fatigue"
        ]
    else:
        severity_grade = "Minimal or No Significant Findings (< 0.5%)"
        clinical_condition = "Normal brain structure or small lesion"
        symptoms = [
            "Often asymptomatic",
            "May experience mild fatigue"
        ]

    # Color masks
    red_mask = np.zeros_like(original_img)
    red_mask[:, :, 2] = 255

    yellow_mask = np.zeros_like(original_img)
    yellow_mask[:, :, 1] = 255
    yellow_mask[:, :, 2] = 255

    green_mask = np.zeros_like(original_img)
    green_mask[:, :, 1] = 255

    # Overlays
    clot_overlay = original_img.copy()
    edema_overlay = original_img.copy()
    midline_overlay = original_img.copy()
    clot_edema_overlay = original_img.copy()
    combined_overlay = original_img.copy()

    clot_overlay[clot_binary == 1] = cv2.addWeighted(clot_overlay, 0.7, red_mask, 0.3, 0)[clot_binary == 1]
    edema_overlay[edema_binary == 1] = cv2.addWeighted(edema_overlay, 0.7, yellow_mask, 0.3, 0)[edema_binary == 1]
    midline_overlay[midline_binary == 1] = cv2.addWeighted(midline_overlay, 0.7, green_mask, 0.3, 0)[midline_binary == 1]
    clot_edema_overlay[clot_binary == 1] = cv2.addWeighted(clot_edema_overlay, 0.7, red_mask, 0.3, 0)[clot_binary == 1]
    clot_edema_overlay[edema_binary == 1] = cv2.addWeighted(clot_edema_overlay, 0.7, yellow_mask, 0.3, 0)[edema_binary == 1]
    combined_overlay[clot_binary == 1] = cv2.addWeighted(combined_overlay, 0.7, red_mask, 0.3, 0)[clot_binary == 1]
    combined_overlay[edema_binary == 1] = cv2.addWeighted(combined_overlay, 0.7, yellow_mask, 0.3, 0)[edema_binary == 1]
    combined_overlay[midline_binary == 1] = cv2.addWeighted(combined_overlay, 0.7, green_mask, 0.3, 0)[midline_binary == 1]

    # Print metrics
    print(f"\n📌 Image: {filename}")
    print(f"🧠 Total Brain Area: {total_brain_area_mm2:.2f} mm²")
    print(f"🟥 Clot Area: {clot_area_mm2:.2f} mm²")
    print(f"🟨 Edema Area: {edema_area_mm2:.2f} mm²")
    print(f"🟣 Midline Shift Area: {midline_shift_area_mm2:.2f} mm²")
    print(f"🧠 Brain Volume: {brain_volume_mm3:.2f} mm³")
    print(f"🟥 Clot Volume: {clot_volume_mm3:.2f} mm³")
    print(f"🟨 Edema Volume: {edema_volume_mm3:.2f} mm³")
    print(f"🟣 Midline Shift Volume: {midline_shift_volume_mm3:.2f} mm³")
    print(f"📊 Clot Volume Percentage: {clot_volume_percentage:.2f}%")
    print(f"📊 Edema Volume Percentage: {edema_volume_percentage:.2f}%")
    print(f"📊 Midline Shift Volume Percentage: {midline_shift_volume_percentage:.2f}%")
    print(f"📊 Normal Brain Volume Percentage: {normal_brain_percentage:.2f}%")
    print(f"📍 Clot Location: {clot_position}")
    print(f"📍 Edema Location: {edema_position}")
    print(f"📍 Midline Shift Severity: {severity_grade}")
    print(f"📍 Clinical Condition: {clinical_condition}")
    print(f"📍 Symptoms: {', '.join(symptoms)}")

    # Titles for visualization
    titles = [
        "Original Image",
        f"Clot: {clot_volume_percentage:.2f}% ({clot_position})",
        f"Edema: {edema_volume_percentage:.2f}% ({edema_position})",
        f"Midline Shift: {midline_shift_volume_percentage:.2f}% ({severity_grade})\n📍 Symptoms: {', '.join(symptoms)}",
        f"Clot+Edema: {(clot_volume_percentage + edema_volume_percentage):.2f}%, Normal: {normal_brain_percentage:.2f}%",
        f"Detected: {(clot_volume_percentage + edema_volume_percentage + midline_shift_volume_percentage):.2f}%, Normal: {normal_brain_percentage:.2f}%"
    ]

    images = [original_img, clot_overlay, edema_overlay, midline_overlay, clot_edema_overlay, combined_overlay]

    fig, axs = plt.subplots(2, 3, figsize=(22, 14))
    for i, ax in enumerate(axs.flat):
        ax.imshow(cv2.cvtColor(images[i], cv2.COLOR_BGR2RGB))
        ax.set_title(titles[i], fontsize=12)
        ax.axis("off")
    plt.tight_layout()
    plt.show()

