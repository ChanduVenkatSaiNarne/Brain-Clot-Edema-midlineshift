# Image dimensions
IMG_HEIGHT, IMG_WIDTH = 256, 256

# Load data for single-class segmentation
def load_single_class_data(image_folder, mask_folder):
    images, masks = [], []
    filenames = sorted([f for f in os.listdir(image_folder) if f.endswith(('.png', '.jpg', '.jpeg'))])

    for filename in filenames:
        image_path = os.path.join(image_folder, filename)
        mask_path = os.path.join(mask_folder, filename)

        if not os.path.exists(image_path) or not os.path.exists(mask_path):
            print(f"❌ Missing image or mask for: {filename}")
            continue

        # Load and preprocess image
        img = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
        img = cv2.resize(img, (IMG_WIDTH, IMG_HEIGHT)) / 255.0
        img = np.expand_dims(img, axis=-1)

        # Load and preprocess mask
        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
        mask = cv2.resize(mask, (IMG_WIDTH, IMG_HEIGHT))
        mask = (mask > 127).astype(np.uint8)
        mask = np.expand_dims(mask, axis=-1)

        images.append(img)
        masks.append(mask)

    return np.array(images), np.array(masks)

